# Quick DMA Test Script - 10 Second Tests
# For slow connections - fast validation only

Write-Host "??????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "?   Quick DMA Test - 75T Validation     ?" -ForegroundColor Cyan
Write-Host "??????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

$pcileechPath = "C:\Tools\PCILeech"
cd $pcileechPath

# Test 1: Quick Memory Display (2 seconds)
Write-Host "[1/3] Memory Display Test (2s)" -ForegroundColor Yellow
Write-Host "???????????????????????????????????????" -ForegroundColor DarkGray
Start-Sleep -Seconds 1
.\pcileech.exe display -min 0x1000 -max 0x1100
Write-Host ""

# Test 2: Small Memory Read Test (3 seconds)
Write-Host "[2/3] Small Read Test (3s)" -ForegroundColor Yellow
Write-Host "???????????????????????????????????????" -ForegroundColor DarkGray
Start-Sleep -Seconds 1
.\pcileech.exe dump -min 0x1000 -max 0x11000 -out test_read.bin
if (Test-Path "test_read.bin") {
    $size = (Get-Item "test_read.bin").Length
    Write-Host "? Read successful: $size bytes" -ForegroundColor Green
    Remove-Item "test_read.bin" -Force
} else {
    Write-Host "? Read failed!" -ForegroundColor Red
}
Write-Host ""

# Test 3: Quick Device Info (2 seconds)
Write-Host "[3/3] Device Info" -ForegroundColor Yellow
Write-Host "???????????????????????????????????????" -ForegroundColor DarkGray
.\pcileech.exe probe -v 2>&1 | Select-String -Pattern "DEVICE|STATUS|CONNECTION" | Select-Object -First 5

Write-Host ""
Write-Host "??????????????????????????????????????????" -ForegroundColor Green
Write-Host "?   Quick Test Complete!                 ?" -ForegroundColor Green
Write-Host "??????????????????????????????????????????" -ForegroundColor Green
Write-Host ""
Write-Host "Next: Run full benchmark when connection improves" -ForegroundColor Cyan
